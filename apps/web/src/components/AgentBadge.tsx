function resolveBrand(agentId: string | null | undefined): BrandSpec {
  if (!agentId) return FALLBACK;
  if (BRANDS[agentId]) return BRANDS[agentId];
  const stripped = agentId.replace(/^custom\./, '');
  return BRANDS[stripped] ?? FALLBACK;
}

export function AgentBadge({
  agentId,
  size = 'md',
  title,
}: {
  agentId: string | null | undefined;
  size?: 'sm' | 'md' | 'lg';
  title?: string;
}) {
  const spec = resolveBrand(agentId);
  const iconPx = size === 'sm' ? 13 : size === 'md' ? 16 : 21;
  return (
    <span
      className={`agent-badge agent-badge-${size}`}
      style={{ background: spec.bg, color: spec.fg ?? '#ffffff' }}
      title={title}
      aria-hidden="true"
    >
      <svg
        width={iconPx}
        height={iconPx}
        viewBox="0 0 24 24"
        fill="currentColor"
        focusable="false"
      >
        {spec.layers.map((layer, index) => (
          <path
            key={index}
            d={layer.d}
            fill={layer.fill ?? 'currentColor'}
            fillRule={layer.fillRule}
            clipRule={layer.fillRule}
            opacity={layer.opacity}
          />
        ))}
      </svg>
    </span>
  );
}
